DAY_OF = {"Upper A": 0, "Lower A": 1, "Upper B": 3, "Lower B": 4}  # Mon, Tue, Thu, Fri
LATE = {"Lower A": 1, "Lower B": 1}  # sometimes a day late (Wed, Sat), never onto another session

